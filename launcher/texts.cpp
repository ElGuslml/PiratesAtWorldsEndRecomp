// Every member is a string (or an array of them): a text a language lacks falls back to English.
static_assert(sizeof(Texts) % sizeof(const char*) == 0);

Texts Complete(const Texts& texts) {
  Texts complete = texts;
  auto* entries = reinterpret_cast<const char**>(&complete);
  auto* english = reinterpret_cast<const char* const*>(&kEnglish);
  for (size_t i = 0; i < sizeof(Texts) / sizeof(const char*); ++i) {
    if (!entries[i]) {
      entries[i] = english[i];
    }
  }
  return complete;
}

